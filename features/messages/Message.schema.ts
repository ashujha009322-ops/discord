import { z } from "zod";
import {
  MAX_ATTACHMENT_SIZE_BYTES,
  MAX_ATTACHMENTS_PER_MESSAGE,
  MAX_FILENAME_LENGTH,
  MAX_TOTAL_ATTACHMENT_BYTES,
  MESSAGES_DEFAULT_PAGE_SIZE,
  MESSAGES_MAX_PAGE_SIZE,
  MESSAGE_MAX_LENGTH,
  isAllowedAttachmentMimeType,
} from "./Constants";

const MB = 1024 * 1024;

export const uuidSchema = z.string().uuid("Invalid ID");

// --- Building blocks ---------------------------------------------------------

const contentMessage = `Message cannot exceed ${MESSAGE_MAX_LENGTH} characters`;

/**
 * Postgres text columns cannot store NUL (\u0000). Without this check such a
 * message would fail at INSERT time and surface as a generic server error.
 */
const hasNoNulChars = (value: string) => !value.includes("\u0000");

const contentField = z
  .string()
  .trim()
  .max(MESSAGE_MAX_LENGTH, contentMessage)
  .refine(hasNoNulChars, "Message contains invalid characters");

/**
 * Duck-typed instead of `z.instanceof(File)`: the `File` class that Next.js
 * hands to server actions is not guaranteed to be the same constructor as the
 * global `File`, which makes `instanceof` checks fail unpredictably.
 */
function isFileLike(value: unknown): value is File {
  return (
    typeof value === "object" &&
    value !== null &&
    typeof (value as File).name === "string" &&
    typeof (value as File).size === "number" &&
    typeof (value as File).type === "string" &&
    typeof (value as File).arrayBuffer === "function"
  );
}

/**
 * Validates what the browser CLAIMS about a file (name, size, MIME type).
 * The server must still sniff real content in the upload pipeline (Stage 5) -
 * `file.type` is client-controlled and can be spoofed.
 */
export const attachmentFileSchema = z
  .custom<File>(isFileLike, "Invalid file")
  .superRefine((file, ctx) => {
    if (!isFileLike(file)) return; // base check already reported the problem

    if (file.size === 0) {
      ctx.addIssue({ code: "custom", message: `"${file.name}" is empty` });
    }
    if (file.size > MAX_ATTACHMENT_SIZE_BYTES) {
      ctx.addIssue({
        code: "custom",
        message: `"${file.name}" is larger than ${MAX_ATTACHMENT_SIZE_BYTES / MB} MB`,
      });
    }
    if (!isAllowedAttachmentMimeType(file.type)) {
      ctx.addIssue({
        code: "custom",
        message: `"${file.name}" has an unsupported file type`,
      });
    }
    if (file.name.length === 0 || file.name.length > MAX_FILENAME_LENGTH) {
      ctx.addIssue({
        code: "custom",
        message: `File names must be 1-${MAX_FILENAME_LENGTH} characters`,
      });
    }
  });

// --- Send ----------------------------------------------------------------------

/**
 * `id` is generated by the client (crypto.randomUUID()). This makes sends
 * idempotent (a retried request hits the primary key instead of creating a
 * duplicate), lets optimistic UI match the realtime echo by id, and gives the
 * upload pipeline a message id before the row exists.
 */
export const sendMessageSchema = z
  .object({
    id: uuidSchema,
    channelId: uuidSchema,
    content: contentField
      .optional()
      .transform((value) => (value ? value : null)),
    files: z
      .array(attachmentFileSchema)
      .max(
        MAX_ATTACHMENTS_PER_MESSAGE,
        `You can attach at most ${MAX_ATTACHMENTS_PER_MESSAGE} files per message`,
      ),
  })
  .superRefine((value, ctx) => {
    if (!value.content && value.files.length === 0) {
      ctx.addIssue({
        code: "custom",
        path: ["content"],
        message: "Message cannot be empty",
      });
    }

    const totalBytes = value.files.reduce((sum, file) => sum + file.size, 0);
    if (totalBytes > MAX_TOTAL_ATTACHMENT_BYTES) {
      ctx.addIssue({
        code: "custom",
        path: ["files"],
        message: `Attachments cannot exceed ${MAX_TOTAL_ATTACHMENT_BYTES / MB} MB in total`,
      });
    }
  });

/** Parsed (output) shape: `content` is `string | null`, `files` is `File[]`. */
export type SendMessageInput = z.infer<typeof sendMessageSchema>;

/** What the client supplies before it is turned into FormData. */
export type SendMessagePayload = {
  id: string;
  channelId: string;
  content?: string;
  files?: File[];
};

/**
 * Field names live in exactly one place: build (client) and parse (server)
 * are defined side by side so they cannot drift apart.
 */
export function buildSendMessageFormData(
  payload: SendMessagePayload,
): FormData {
  const formData = new FormData();
  formData.set("id", payload.id);
  formData.set("channelId", payload.channelId);
  if (payload.content) formData.set("content", payload.content);
  for (const file of payload.files ?? []) formData.append("files", file);
  return formData;
}

export function parseSendMessageFormData(formData: FormData) {
  const content = formData.get("content");

  const files = formData.getAll("files").filter(
    (entry): entry is File =>
      typeof entry !== "string" &&
      // An empty <input type="file"> serializes as a nameless 0-byte entry.
      !(entry.size === 0 && entry.name === ""),
  );

  return sendMessageSchema.safeParse({
    id: formData.get("id") ?? undefined,
    channelId: formData.get("channelId") ?? undefined,
    content: typeof content === "string" ? content : undefined,
    files,
  });
}

// --- Edit ----------------------------------------------------------------------

/**
 * Empty content is allowed by the schema because a message that still has
 * attachments may legitimately end up with no text. The action enforces
 * "must keep text or at least one attachment" against the database.
 */
export const editMessageSchema = z.object({
  messageId: uuidSchema,
  content: contentField,
});
export type EditMessageInput = z.infer<typeof editMessageSchema>;

// --- Delete --------------------------------------------------------------------

export const deleteMessageSchema = z.object({
  messageId: uuidSchema,
});
export type DeleteMessageInput = z.infer<typeof deleteMessageSchema>;

// --- Read (paginated history) ----------------------------------------------------

export const messageCursorSchema = z.object({
  createdAt: z.string().datetime(),
  id: uuidSchema,
});

export const getMessagesSchema = z.object({
  channelId: uuidSchema,
  /** Omit for the newest page; pass `nextCursor` from the previous page to go back in time. */
  before: messageCursorSchema.optional(),
  limit: z
    .number()
    .int()
    .min(1)
    .max(MESSAGES_MAX_PAGE_SIZE)
    .default(MESSAGES_DEFAULT_PAGE_SIZE),
});
/** Input shape: `limit` is optional for callers. */
export type GetMessagesInput = z.input<typeof getMessagesSchema>;
