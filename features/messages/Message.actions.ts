"use server";

import { prisma } from "@/lib/prisma";
import {
  assertCanSend,
  requireChannelAccess,
  requireMessageAccess,
} from "@/lib/Authorization";
import { ActionError } from "../messages/Errors";
import { messageSelect, toMessageDTO } from "../messages/messageSelect";
import { canDeleteMessage, canEditMessage } from "../messages/Permissions";
import {
  scheduleBroadcastMessageCreated,
  scheduleBroadcastMessageDeleted,
  scheduleBroadcastMessageUpdated,
} from "@/features/messages/Realtime";
import { runAction } from "@/features/messages/Run-action";
import { parseOrThrow, validationError } from "../messages/Validation";
import {
  deleteMessageSchema,
  editMessageSchema,
  getMessagesSchema,
  parseSendMessageFormData,
  type DeleteMessageInput,
  type EditMessageInput,
  type GetMessagesInput,
} from "../messages/Message.schema";
import type { MessageDTO, MessagePage } from "../messages/Types";

// NOTE: a "use server" file may only export async functions. Keep helpers,
// constants and schemas in other modules.

// Scalar-only select for newly created messages: `access.user` is already in
// memory from `requireChannelAccess`, and a brand-new message cannot have READY
// attachments yet.
const createdMessageSelect = {
  id: true,
  channelId: true,
  authorId: true,
  content: true,
  createdAt: true,
  editedAt: true,
} as const;

/**
 * Send a message. Takes FormData (not a plain object) because Stage 5 adds
 * file attachments to the same request. Fields: id, channelId, content?, files*.
 *
 * Retry-safe: `id` is generated by the client. If the same user re-sends the
 * same id to the same channel (flaky network, double click), they get the
 * existing message back instead of a duplicate or an error.
 */
export async function sendMessage(formData: FormData) {
  return runAction("sendMessage", async (): Promise<MessageDTO> => {
    const t0 = performance.now();

    const parsed = parseSendMessageFormData(formData);
    if (!parsed.success) throw validationError(parsed.error);
    const { id, channelId, content, files } = parsed.data;

    // Stage 5 replaces this guard with the real upload pipeline.
    if (files.length > 0) {
      throw new ActionError("VALIDATION", "Attachments are not enabled yet.", {
        files: ["Attachments are not enabled yet."],
      });
    }

    const access = await requireChannelAccess(channelId);
    assertCanSend(access);
    const tAccess = performance.now();

    let dto: MessageDTO;

    try {
      const row = await prisma.message.create({
        data: {
          id,
          channelId: access.channelId,
          // Always the authenticated user - never anything from the client.
          authorId: access.userId,
          content,
        },
        select: createdMessageSelect,
      });

      dto = {
        id: row.id,
        channelId: row.channelId,
        content: row.content,
        createdAt: row.createdAt.toISOString(),
        editedAt: row.editedAt ? row.editedAt.toISOString() : null,
        author: {
          id: access.user.id,
          username: access.user.username,
          displayName: access.user.displayName,
          avatarKey: access.user.avatarKey,
        },
        attachments: [],
      };
    } catch (error) {
      // The create failed. If the row already exists AND is the caller's own
      // message in this channel, this is a retry: return it. (Checking the row
      // is more robust than pattern-matching a driver-specific error code.)
      const existing = await prisma.message.findUnique({
        where: { id },
        select: messageSelect,
      });
      if (!existing) throw error;

      if (
        existing.authorId === access.userId &&
        existing.channelId === access.channelId
      ) {
        dto = toMessageDTO(existing);
      } else {
        throw new ActionError(
          "VALIDATION",
          "This message id is already in use.",
          { id: ["This message id is already in use."] },
        );
      }
    }

    const tDb = performance.now();

    // Broadcast AFTER the commit without blocking the sender's response.
    // On retries too: if the first attempt's broadcast was lost, the retry
    // heals it. Clients de-duplicate by id, and `scheduleBroadcast*` never throws.
    scheduleBroadcastMessageCreated(dto);

    if (process.env.NODE_ENV === "development") {
      console.info(
        `[messages] sendMessage timing: access=${(tAccess - t0).toFixed(0)}ms db=${(tDb - tAccess).toFixed(0)}ms`,
      );
    }

    return dto;
  });
}

/**
 * One page of history, returned oldest -> newest. Omit `before` for the newest
 * page; pass the previous `nextCursor` to go further back.
 */
export async function getMessages(input: GetMessagesInput) {
  return runAction("getMessages", async (): Promise<MessagePage> => {
    const { channelId, before, limit } = parseOrThrow(getMessagesSchema, input);
    const access = await requireChannelAccess(channelId);

    const beforeDate = before ? new Date(before.createdAt) : null;

    // Keyset pagination on (createdAt DESC, id DESC) - the exact order of the
    // @@index([channelId, createdAt desc, id desc]) on Message. Fetch one extra
    // row so we know whether an older page exists without a COUNT query.
    const rows = await prisma.message.findMany({
      where: {
        channelId: access.channelId,
        deletedAt: null,
        ...(before && beforeDate
          ? {
              OR: [
                { createdAt: { lt: beforeDate } },
                { createdAt: beforeDate, id: { lt: before.id } },
              ],
            }
          : {}),
      },
      orderBy: [{ createdAt: "desc" }, { id: "desc" }],
      take: limit + 1,
      select: messageSelect,
    });

    const hasMore = rows.length > limit;
    const page = hasMore ? rows.slice(0, limit) : rows;
    const oldest = page[page.length - 1];

    return {
      messages: page.map((row) => toMessageDTO(row)).reverse(),
      nextCursor:
        hasMore && oldest
          ? { createdAt: oldest.createdAt.toISOString(), id: oldest.id }
          : null,
      viewer: {
        author: {
          id: access.user.id,
          username: access.user.username,
          displayName: access.user.displayName,
          avatarKey: access.user.avatarKey,
        },
        isGuildOwner: access.isGuildOwner,
        timeoutUntil: access.timeoutUntil
          ? access.timeoutUntil.toISOString()
          : null,
      },
    };
  });
}

/**
 * Edit message text. Authors can edit their own messages; the guild owner can
 * edit anyone's. Attachments are not editable in this version.
 */
export async function editMessage(input: EditMessageInput) {
  return runAction("editMessage", async (): Promise<MessageDTO> => {
    const { messageId, content } = parseOrThrow(editMessageSchema, input);
    const { access, message } = await requireMessageAccess(messageId);

    if (!canEditMessage(access, message)) {
      throw new ActionError(
        "FORBIDDEN",
        "You can only edit your own messages.",
      );
    }

    const nextContent = content === "" ? null : content;

    // A message must keep either text or at least one attachment.
    if (nextContent === null && message.attachments.length === 0) {
      throw new ActionError("VALIDATION", "Message cannot be empty.", {
        content: ["Message cannot be empty."],
      });
    }

    // Nothing changed: don't bump `editedAt` (it would show a bogus "(edited)").
    if (nextContent === message.content) return toMessageDTO(message);

    let dto: MessageDTO;

    try {
      const row = await prisma.message.update({
        where: { id: message.id },
        data: { content: nextContent, editedAt: new Date() },
        select: messageSelect,
      });
      dto = toMessageDTO(row);
    } catch (error) {
      // Most likely the message was deleted between our read and this write.
      const stillExists = await prisma.message.findUnique({
        where: { id: message.id },
        select: { id: true },
      });
      if (!stillExists)
        throw new ActionError("NOT_FOUND", "Message not found.");
      throw error;
    }

    scheduleBroadcastMessageUpdated(dto);
    return dto;
  });
}

/**
 * Hard-delete a message. Authors can delete their own; the guild owner can
 * delete anyone's. Clients should treat NOT_FOUND as "already deleted".
 */
export async function deleteMessage(input: DeleteMessageInput) {
  return runAction(
    "deleteMessage",
    async (): Promise<{ id: string; channelId: string }> => {
      const { messageId } = parseOrThrow(deleteMessageSchema, input);
      const { access, message } = await requireMessageAccess(messageId);

      if (!canDeleteMessage(access, message)) {
        throw new ActionError(
          "FORBIDDEN",
          "You can only delete your own messages.",
        );
      }

      // Stage 6 replaces this guard with "remove the files from Storage first".
      // Until then, refuse rather than orphan files in the bucket.
      if (message.attachments.length > 0) {
        throw new ActionError(
          "STORAGE_ERROR",
          "Deleting messages with attachments is not available yet.",
        );
      }

      // deleteMany (not delete): a concurrent delete yields count 0 instead of
      // throwing. The DB cascades to reactions, mentions, pins, etc.
      const { count } = await prisma.message.deleteMany({
        where: { id: message.id },
      });
      if (count === 0) throw new ActionError("NOT_FOUND", "Message not found.");

      const deleted = { id: message.id, channelId: message.channelId };
      scheduleBroadcastMessageDeleted(deleted);
      return deleted;
    },
  );
}
